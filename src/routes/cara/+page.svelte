<h1 class="font-display font-bold text-4xl md:text-5xl">Cara deteksi buzzer</h1>
<p class="mt-3 max-w-2xl text-[#e9d5ff]/85">Panduan praktis membaca akun buzzer dari perilaku publiknya — bukan dari tuduhan, tapi dari bukti yang bisa kamu cek sendiri.</p>

<section class="grid md:grid-cols-2 gap-5 mt-8">
  <article class="bg-white text-[#2a0a38] rounded-3xl p-6">
    <p class="font-display font-bold text-xl text-[#be185d]">1. Cek umur akun</p>
    <p class="mt-2 text-[#6b3a7d]">Buka profil, lihat kapan akun dibuat. Akun berumur hari/minggu yang langsung rajin komen dan promosi adalah sinyal paling murah.</p>
  </article>
  <article class="bg-white text-[#2a0a38] rounded-3xl p-6">
    <p class="font-display font-bold text-xl text-[#7e22ce]">2. Bandingkan following vs followers</p>
    <p class="mt-2 text-[#6b3a7d]">Following jauh lebih besar dari followers = pola follow massal. Akun organik biasanya following lebih kecil.</p>
  </article>
  <article class="bg-white text-[#2a0a38] rounded-3xl p-6">
    <p class="font-display font-bold text-xl text-[#be185d]">3. Hitung ritme posting</p>
    <p class="mt-2 text-[#6b3a7d]">Lihat 20 postingan terakhir. Belasan post/hari, jamnya acak, tidak ada jeda tidur — itu ritme mesin atau shift buzzer.</p>
  </article>
  <article class="bg-white text-[#2a0a38] rounded-3xl p-6">
    <p class="font-display font-bold text-xl text-[#7e22ce]">4. Bandingkan teks komentar</p>
    <p class="mt-2 text-[#6b3a7d]">Tempel komentarnya ke Detektor. Frasa sama persis di banyak postingan berbeda = template. Apalagi kalau selalu bareng link promo.</p>
  </article>
</section>

<section class="mt-8 bg-[#24102e] rounded-3xl p-6 border border-white/10">
  <h2 class="font-display font-bold text-2xl">Checklist cepat sebelum menyimpulkan</h2>
  <ul class="mt-4 grid gap-2 text-[#e9d5ff]/90 list-disc pl-5">
    <li>Minimal 3 sinyal berbeda kena — jangan vonis dari 1 tanda.</li>
    <li>Cek apakah akun lain memposting teks yang sama di waktu yang sama (indikasi koordinasi).</li>
    <li>Bedakan buzzer (dibayar promosi) dengan spam biasa dan bot — penanganannya beda.</li>
    <li>Simpan bukti: screenshot + link + tanggal, sebelum akunnya dihapus atau diganti nama.</li>
    <li>Kalau yakin melanggar, laporkan lewat fitur Report resmi — jangan balas spam dengan spam.</li>
  </ul>
</section>

